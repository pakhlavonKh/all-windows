function CountUp({ 
  value, 
  duration = 1.8, 
  suffix = '', 
  prefix = '' 
}: { 
  value: number | string; 
  duration?: number; 
  suffix?: string; 
  prefix?: string; 
}) {
  const ref = useRef<HTMLSpanElement>(null);
  const isInView = useInView(ref, { once: true, margin: '-10px' });
  
  let targetNum = typeof value === 'number' ? value : 0;
  let targetPrefix = prefix;
  let targetSuffix = suffix;

  if (typeof value === 'string') {
    const match = value.match(/^([^\d]*)([\d\s,.]+)(.*)$/);
    if (match) {
      targetPrefix = prefix || match[1];
      targetNum = parseFloat(match[2].replace(/\s/g, '').replace(',', '.')) || 0;
      targetSuffix = suffix || match[3];
    }
  }

  const [displayValue, setDisplayValue] = useState(0);
  const prevValueRef = useRef(0);

  useEffect(() => {
    if (!isInView) return;
    const from = prevValueRef.current;
    const to = targetNum;
    const controls = animate(from, to, {
      duration,
      ease: [0.16, 1, 0.3, 1],
      onUpdate(latest) {
        setDisplayValue(latest);
      },
      onComplete() {
        prevValueRef.current = to;
      }
    });
    return () => controls.stop();
  }, [isInView, targetNum, duration]);

  const formattedNum = Math.round(displayValue).toLocaleString('ru-RU');

  return (
    <span ref={ref} className="tabular-nums">
      {targetPrefix}
      {isInView ? formattedNum : '0'}
      {targetSuffix}
    </span>
  );
}

function UniqueSelect({
  label,
  value,
  onChange,
  options,
  placeholder = 'Выберите...',
  testId,
}: {
  label: string;
  value: string;
  onChange: (val: string) => void;
  options: { label: string; value: string; badge?: string; desc?: string }[];
  placeholder?: string;
  testId?: string;
}) {
  const [open, setOpen] = useState(false);
  const containerRef = useRef<HTMLDivElement>(null);

  const selectedOption = options.find(o => o.value === value);

  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (containerRef.current && !containerRef.current.contains(event.target as Node)) {
        setOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  return (
    <div ref={containerRef} className={`relative border-b border-black/20 pb-3 transition-all min-w-0 max-w-full ${open ? 'z-50' : 'z-10'}`}>
      <span className="block text-xs font-semibold text-black/70 mb-1.5 truncate">{label}</span>
      <button
        type="button"
        onClick={() => setOpen(!open)}
        className="flex w-full items-center justify-between gap-2 text-left py-1 text-base md:text-lg font-bold text-[#151515] outline-none transition group cursor-pointer min-w-0"
        data-testid={testId}
      >
        <span className="truncate min-w-0 flex-1">{selectedOption ? selectedOption.label : placeholder}</span>
        <ChevronDown size={18} className={`text-black/60 transition-transform duration-200 shrink-0 ${open ? 'rotate-180 text-[#816a3f]' : ''}`} />
      </button>

      <AnimatePresence>
        {open && (
          <motion.div
            initial={{ opacity: 0, y: 8, scale: 0.98 }}
            animate={{ opacity: 1, y: 0, scale: 1 }}
            exit={{ opacity: 0, y: 4, scale: 0.98 }}
            transition={{ duration: 0.15 }}
            className="absolute left-0 right-0 top-[calc(100%+6px)] z-100 overflow-hidden rounded-2xl border border-[#c6a15b]/40 bg-[#171717] shadow-2xl backdrop-blur-xl"
          >
            <div className="custom-scrollbar max-h-64 overflow-y-auto p-2 space-y-1">
              {options.map((opt) => {
                const isSelected = opt.value === value;
                return (
                  <button
                    key={opt.value}
                    type="button"
                    onClick={() => {
                      onChange(opt.value);
                      setOpen(false);
                    }}
                    className={`flex w-full items-center justify-between gap-3 rounded-xl px-3.5 py-2.5 text-left text-xs sm:text-sm transition cursor-pointer ${
                      isSelected
                        ? 'bg-[#c6a15b] font-bold text-black shadow-sm'
                        : 'text-white/85 hover:bg-white/10 hover:text-white'
                    }`}
                  >
                    <div className="flex flex-col truncate pr-2">
                      <span className="truncate">{opt.label}</span>
                      {opt.desc && (
                        <span className={`text-[10px] truncate ${isSelected ? 'text-black/70 font-normal' : 'text-white/45'}`}>
                          {opt.desc}
                        </span>
                      )}
                    </div>
                    <div className="flex items-center gap-2 shrink-0">
                      {opt.badge && (
                        <span className={`rounded-full px-2 py-0.5 text-[9px] font-mono ${
                          isSelected ? 'bg-black/20 text-black' : 'bg-white/10 text-white/70'
                        }`}>
                          {opt.badge}
                        </span>
                      )}
                      {isSelected && <Check size={14} className="shrink-0 text-black" />}
                    </div>
                  </button>
                );
              })}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

function NumberStepperInput({
  label,
  value,
  onChange,
  placeholder = '1000',
  min = 100,
  max = 10000,
  step = 50,
  testId,
}: {
  label: string;
  value: string;
  onChange: (val: string) => void;
  placeholder?: string;
  min?: number;
  max?: number;
  step?: number;
  testId?: string;
}) {
  const handleStep = (delta: number) => {
    const current = parseInt(value, 10) || parseInt(placeholder, 10) || 0;
    const next = Math.max(min, Math.min(max, current + delta));
    onChange(String(next));
  };

  return (
    <div className="border-b border-black/20 pb-2 min-w-0">
      <span className="block text-[11px] sm:text-xs font-semibold text-black/70 mb-1 truncate" title={label}>{label}</span>
      <div className="flex items-center justify-between gap-1 min-w-0">
        <input
          type="number"
          value={value}
          onChange={(e) => onChange(e.target.value)}
          placeholder={placeholder}
          min={min}
          max={max}
          className="w-full min-w-0 bg-transparent py-1 text-sm sm:text-base font-bold text-[#151515] outline-none [appearance:textfield] [&::-webkit-outer-spin-button]:appearance-none [&::-webkit-inner-spin-button]:appearance-none"
          data-testid={testId}
        />
        <div className="flex flex-col items-center justify-center rounded-lg border border-black/15 bg-black/5 p-0.5 shadow-xs shrink-0">
          <button
            type="button"
            onClick={() => handleStep(step)}
            aria-label="Увеличить"
            className="flex size-4.5 items-center justify-center rounded text-black/60 hover:bg-[#c6a15b] hover:text-black transition-colors cursor-pointer active:scale-90"
          >
            <ChevronUp size={12} strokeWidth={2.5} />
          </button>
          <button
            type="button"
            onClick={() => handleStep(-step)}
            aria-label="Уменьшить"
            className="flex size-4.5 items-center justify-center rounded text-black/60 hover:bg-[#c6a15b] hover:text-black transition-colors cursor-pointer active:scale-90"
          >
            <ChevronDown size={12} strokeWidth={2.5} />
          </button>
        </div>
      </div>
    </div>
  );
}

