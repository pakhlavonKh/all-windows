function App() { 
  const [lang, setLang] = useState<Lang>('ru'); 
  const [modal, setModal] = useState(false); 
  const [initialProduct, setInitialProduct] = useState(''); 
  const [initialColor, setInitialColor] = useState(''); 
  
  const openEstimate = (p = '', c = '') => { 
    setInitialProduct(p); 
    setInitialColor(c); 
    setModal(true); 
  }; 

  return (
    <QueryClientProvider client={queryClient}>
      <TooltipProvider>
        <ErrorBoundary>
          <Shell lang={lang} setLang={setLang} onEstimate={openEstimate}>
            <RouterView lang={lang} onEstimate={openEstimate} />
          </Shell>
        </ErrorBoundary>
        <Toaster />
      </TooltipProvider>
      <EstimateModal open={modal} initialProduct={initialProduct} initialColor={initialColor} onClose={() => setModal(false)} />
    </QueryClientProvider>
  ); 
}

